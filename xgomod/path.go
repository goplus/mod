package xgomod

import (
	"path/filepath"
	"strings"
)

// pathWithin reports whether target is root itself or a descendant of root.
// filepath.Rel can return an absolute path on some platforms (for example,
// when the paths are on different volumes); that is never a descendant.
func pathWithin(root, target string) bool {
	rel, err := filepath.Rel(root, target)
	if err != nil || filepath.IsAbs(rel) {
		return false
	}
	return rel == "." || (rel != ".." && !strings.HasPrefix(rel, ".."+string(filepath.Separator)))
}
